def _sanitize_oidc_env(value: str) -> str:
    cleaned = (value or "").strip()
    lowered = cleaned.lower()
    if not cleaned:
        return ""
    if cleaned.upper().startswith("CHANGE_ME_"):
        return ""
    if "your-oidc-provider" in lowered:
        return ""
    if lowered in {"your-client-id", "your-client-secret"}:
        return ""
    return cleaned


